-- 分钟原始数据在 Parquet，PG 只记录可见分区和采集批次。
CREATE SCHEMA src_minprice;

CREATE TABLE src_minprice._batch (
    _batch_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset text NOT NULL,
    window_start text,
    window_end text,
    source_cursor text,
    row_count bigint NOT NULL,
    payload_digest char(64) NOT NULL,
    status text NOT NULL,
    detail text,
    started_at timestamptz NOT NULL,
    finished_at timestamptz
);

CREATE TABLE src_minprice.lake_partition (
    dataset text NOT NULL,
    trade_date date NOT NULL,
    file_name text NOT NULL,
    row_count bigint NOT NULL,
    code_count integer NOT NULL,
    content_digest char(64) NOT NULL,
    file_sha256 char(64) NOT NULL,
    file_bytes bigint NOT NULL,
    source_table text NOT NULL,
    _batch_id bigint NOT NULL REFERENCES src_minprice._batch,
    _ingested_at timestamptz NOT NULL,
    PRIMARY KEY (dataset, trade_date)
);
