@pytest.mark.unit
def test_real_volumes_that_trigger_heap_fallback_match_pandas(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    calls: list[tuple[int, int]] = []
    original = legacy_sort._heapsort

    def spy(keys, tosort, pl, pr):  # type: ignore[no-untyped-def]
        calls.append((pl, pr))
        return original(keys, tosort, pl, pr)

    monkeypatch.setattr(legacy_sort, "_heapsort", spy)
    retained = _VOLS[1:]
    got = legacy_sort.legacy_descending_order(retained)
    assert calls, "这组输入应当触发堆排序兜底，否则回归没有覆盖目标分支"
    want = [int(i) for i in pd.Series(retained, dtype="float64").sort_values(ascending=False).index]
    assert got == want


@pytest.mark.unit
def test_heapsort_keeps_distinct_keys_in_numpy_order() -> None:
    # 无并列时堆排序的结果与 numpy argsort(kind="heapsort") 一致。并列位置的先后由上面的 pandas 对拍验证：
    # 直接调用 numpy 的 heapsort 在并列位置上与本移植不同，不能作为并列顺序的依据。
    keys = [float(v) for v in [5, 1, 9, 3, 7, 2, 8, 4, 6, 0]]
    tosort = list(range(len(keys)))
    legacy_sort._heapsort(keys, tosort, 0, len(keys) - 1)
    assert tosort == np.argsort(np.array(keys), kind="heapsort").tolist()
